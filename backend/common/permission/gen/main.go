// Command gen regenerates permission_gen.go from permission.json. It is the
// single source of truth for the permission catalog: add a permission there,
// then run `go generate ./backend/common/permission`.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"strings"
)

type catalog struct {
	Permissions []struct {
		Name string `json:"name"`
		ID   string `json:"id"`
	} `json:"permissions"`
}

func main() {
	data, err := os.ReadFile("permission.json")
	if err != nil {
		panic(err)
	}
	var c catalog
	if err := json.Unmarshal(data, &c); err != nil {
		panic(err)
	}
	if len(c.Permissions) == 0 {
		panic("permission.json contains no permissions")
	}

	seen := map[string]bool{}
	var b strings.Builder
	write := func(s string) {
		if _, err := b.WriteString(s); err != nil {
			panic(err)
		}
	}
	printf := func(format string, args ...any) {
		if _, err := fmt.Fprintf(&b, format, args...); err != nil {
			panic(err)
		}
	}
	write("// Code generated by go generate ./backend/common/permission; DO NOT EDIT.\n\n")
	write("package permission\n\n")
	write("// Permission constants mirror permission.json; the string is the\n")
	write("// fine-grained capability used by proto annotations and role matrices.\n")
	write("const (\n")
	for _, p := range c.Permissions {
		if p.Name == "" || !strings.HasPrefix(p.ID, "laelia.") {
			panic(fmt.Sprintf("invalid permission entry %+v", p))
		}
		if seen[p.Name] || seen[p.ID] {
			panic(fmt.Sprintf("duplicate permission entry %q / %q", p.Name, p.ID))
		}
		seen[p.Name] = true
		seen[p.ID] = true
		printf("\t%s Permission = %q\n", p.Name, p.ID)
	}
	write(")\n\n")
	write("// allPermissions is the complete, authoritative list of valid permission\n")
	write("// strings, derived from permission.json. It feeds allPermissionsMap and\n")
	write("// AllPermissions.\n")
	write("var allPermissions = []Permission{\n")
	for _, p := range c.Permissions {
		printf("\t%s,\n", p.Name)
	}
	write("}\n\n")
	write("var allPermissionsMap = func() map[Permission]bool {\n")
	write("\tm := make(map[Permission]bool, len(allPermissions))\n")
	write("\tfor _, p := range allPermissions {\n\t\tm[p] = true\n\t}\n\treturn m\n}()\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("permission_gen.go", src, 0o644); err != nil {
		panic(err)
	}
}
